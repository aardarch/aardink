package com.aardarch.aardink.sample.benchmark

import androidx.benchmark.macro.junit4.BaselineProfileRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * `:sample`'s baseline profile: starting the app, opening an editor, typing and scrolling. A
 * profile for the sample only; `:editor` ships none (docs/AARDINK_ROADMAP.md §8.4), so a host
 * collects its own over its own screens.
 *
 * `./gradlew :sample:generateBaselineProfile` runs it and writes the profile into `:sample`.
 */
@RunWith(AndroidJUnit4::class)
class BaselineProfileGenerator {

    @get:Rule
    val rule = BaselineProfileRule()

    @Test
    fun generate() = rule.collect(packageName = TARGET_PACKAGE, includeInStartupProfile = true) {
        pressHome()
        startActivityAndWait()
        openKotlinEditor()
        typeAndScroll()
    }
}
